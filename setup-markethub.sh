#!/usr/bin/env bash
# MarketHub installer: scaffolds Laravel 12 + Inertia + Vue, applies the MarketHub code,
# migrates and seeds the database, builds the front end and runs the tests.
# Usage (inside an empty repo / Codespace folder):  bash setup-markethub.sh
set -euo pipefail

WORK="$(pwd)"
SELF="$(readlink -f "$0")"
PAYLOAD_DIR="$(mktemp -d)"

# --- unpack the embedded project files ---
sed -n '/^__PAYLOAD__$/,$p' "$SELF" | tail -n +2 | base64 -d | tar -xz -C "$PAYLOAD_DIR"
if [ "${MH_EXTRACT_ONLY:-}" = "1" ]; then echo "$PAYLOAD_DIR"; exit 0; fi

command -v composer >/dev/null || { echo "Composer is required"; exit 1; }
command -v npm >/dev/null || { echo "Node/npm is required"; exit 1; }

BUILD="$(mktemp -d)/app"
composer create-project laravel/laravel:^12.0 "$BUILD" --no-interaction
cp -a "$BUILD"/. "$WORK"/
rm -rf "$BUILD"
cd "$WORK"

composer require inertiajs/inertia-laravel:^2.0 --no-interaction
npm install vue@^3.5 @inertiajs/vue3@^2.0 @vitejs/plugin-vue

cp -a "$PAYLOAD_DIR"/. .
rm -f tests/Feature/ExampleTest.php tests/Unit/ExampleTest.php
sed -i 's/^APP_NAME=.*/APP_NAME=MarketHub/' .env .env.example || true
grep -q '^APP_TIMEZONE=' .env.example || echo 'APP_TIMEZONE=Asia/Karachi' >> .env.example
sed -i 's/^APP_TIMEZONE=.*/APP_TIMEZONE=Asia\/Karachi/' .env 2>/dev/null || true

php artisan migrate:fresh --seed --force
npm run build
php artisan test || echo "Some tests failed - paste the output and I will fix them."

echo
echo "Done. Start the app with:  composer run dev"
echo "Demo login: customer@markethub.test / password (also vendor1@, admin@markethub.test)"
exit 0
